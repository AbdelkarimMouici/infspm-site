const dictionaries: Record<AdminLang, Record<AdminKey, string>> = { ar, fr };

export function translator(lang: AdminLang) {
  return (key: AdminKey, n?: string | number): string => dictionaries[lang][key].replace('{n}', String(n ?? ''));
}

export type T = ReturnType<typeof translator>;

export function storedLang(): AdminLang {
  try {
    return localStorage.getItem('admin-lang') === 'fr' ? 'fr' : 'ar';
  } catch {
    return 'ar';
  }
}

export function storeLang(lang: AdminLang): void {
  try {
    localStorage.setItem('admin-lang', lang);
  } catch {
    /* ignore */
  }
}
